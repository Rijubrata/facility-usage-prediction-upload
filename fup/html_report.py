def _pct(v):
    return f"{v * 100:.1f}%"


def _fmt(metric: str, v: float) -> str:
    if any(t in metric for t in ("MAE", "error", "Log loss", "matched per")):
        return f"{v:.2f}"
    return _pct(v)


def write_html(rev: pd.DataFrame, summ: pd.DataFrame, err: pd.DataFrame, path) -> None:
    s = summ.set_index("metric")
    tile_specs = [
        ("Facility accuracy", "Facility", "Accuracy (top-1)"),
        ("Usage day exact", "Usage day", "Exact calendar day"),
        ("Usage hour exact", "Usage hour", "Exact hour"),
        (f"Nudge within {C.NUDGE_TOLERANCE_MIN} min", "Notification time", f"Within +/-{C.NUDGE_TOLERANCE_MIN} min of actual booking"),
        ("Mean output accuracy", "Overall", "Mean output accuracy (avg of 4 match rates)"),
        ("All 4 outputs match", "Overall", "All 4 outputs match"),
    ]
    tiles = "".join(
        f'<div class="tile"><div class="k">{html.escape(t)}</div><div class="v">{_pct(s.loc[m, "model"])}</div>'
        f'<div class="b">habit baseline {_pct(s.loc[m, "baseline_habit"])}</div></div>' for t, _, m in tile_specs)
    summary = "".join(
        f"<tr><td>{html.escape(r.output)}</td><td>{html.escape(r.metric)}</td>"
        f'<td class="num"><b>{_fmt(r.metric, r.model)}</b></td><td class="num">{_fmt(r.metric, r.baseline_habit)}</td>'
        f'<td class="num">{_fmt(r.metric, r.baseline_popularity)}</td></tr>' for r in summ.itertuples())
    errs = "".join(
        f"<tr><td>{html.escape(r.segment)}</td><td>{html.escape(str(r.value))}</td><td class='num'>{r.n}</td>"
        + "".join(f"<td class='num'>{_pct(getattr(r, c))}</td>" for c in
                  ["facility_acc", "day_acc", "hour_acc", "nudge_acc", "mean_output_acc", "all4"]) + "</tr>"
        for r in err.itertuples())
    data = [dict(id=r.record_ref, res=r.resident, at=r.predicted_at,
                 h=r.past, pf=r.pred_facility, pd=r.pred_day, pt=r.pred_use_time, pn=r.pred_nudge,
                 af=r.act_facility, ad=r.act_day, at2=r.act_use_time, ab=r.act_booked_at,
                 m=[bool(r.facility_match), bool(r.day_match), bool(r.hour_match), bool(r.nudge_match)],
                 k=int(r.outputs_matched))
            for r in rev.rename(columns={rev.columns[4]: "past"}).itertuples()]
    facopts = "".join(f'<option>{html.escape(C.FACILITY_LABEL[f])}</option>' for f in C.FACILITY_IDS)
    intro = (f"{len(rev):,} holdout bookings created between {C.TEST_START:%d %b %Y} and "
             f"{C.DATA_END - pd.Timedelta(days=1):%d %b %Y}, never used for fitting or tuning. Each prediction is "
             f"made when the resident created their previous booking, using only information available then. "
             f"Day = exact calendar date; hour = exact start hour; nudge matches if within "
             f"&plusmn;{C.NUDGE_TOLERANCE_MIN} min of when the resident actually booked.")
    page = (PAGE.replace("__INTRO__", intro).replace("__TILES__", tiles).replace("__SUMMARY__", summary)
            .replace("__ERR__", errs).replace("__FACOPTS__", facopts)
            .replace("__DATA__", json.dumps(data, separators=(",", ":")).replace("</", "<\\/")))
    path.write_text(page, encoding="utf-8")
    print(f"wrote {path}")
